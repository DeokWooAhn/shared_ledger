/// [date]가 공휴일이면 그 이름, 아니면 null. 시각은 보지 않는다.
String? koreanHoliday(DateTime date) {
  final month = date.month.toString().padLeft(2, '0');
  final day = date.day.toString().padLeft(2, '0');
  return _holidays['${date.year}-$month-$day'];
}
